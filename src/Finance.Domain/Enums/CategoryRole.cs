namespace Finance.Domain.Enums;

/// <summary>
/// Роль категории. Единственный признак, по которому «Прочее» и служебные категории
/// отличаются от обычных: строкового ключа стартового набора в базе нет, а название
/// пользователь вправе изменить.
/// </summary>
public enum CategoryRole
{
    /// <summary>
    /// Значение неинициализированной переменной. Настоящей ролью категории не бывает.
    /// </summary>
    Unknown = 0,

    /// <summary>
    /// Обычная категория, роль её не защищает: подкатегория переименовывается,
    /// переносится и удаляется, а группа не удаляется и не переносится при любой роли.
    /// </summary>
    Normal = 1,

    /// <summary>
    /// Приёмник группы «Прочее»: сюда переезжают операции удаляемых подкатегорий.
    /// </summary>
    Other = 2,

    /// <summary>
    /// Служебная категория. Служебной группе приёмник не нужен.
    /// </summary>
    Service = 3
}
