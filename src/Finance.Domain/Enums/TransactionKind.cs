namespace Finance.Domain.Enums;

/// <summary>
/// Вид операции. Определяет знак суммы в балансе; сама сумма всегда положительна.
/// </summary>
public enum TransactionKind
{
    /// <summary>
    /// Значение неинициализированной переменной. Настоящим видом операции не бывает.
    /// </summary>
    Unknown = 0,

    /// <summary>
    /// Расход: уменьшает баланс счёта списания.
    /// </summary>
    Expense = 1,

    /// <summary>
    /// Доход: увеличивает баланс счёта списания.
    /// </summary>
    Income = 2,

    /// <summary>
    /// Перевод между двумя своими счетами. Не доход и не расход: в отчёт не входит.
    /// </summary>
    Transfer = 3
}
