namespace Finance.Domain.Enums;

/// <summary>
/// Валюта счёта. Конвертация между валютами не выполняется никогда.
/// </summary>
public enum Currency
{
    /// <summary>
    /// Значение неинициализированной переменной. Настоящей валютой не бывает и в базу не попадает.
    /// </summary>
    Unknown = 0,

    /// <summary>
    /// Рубль. Валюта итогов дня и отчёта — единственная, в которой считаются общие суммы.
    /// </summary>
    RUB = 1,

    /// <summary>
    /// Доллар США.
    /// </summary>
    USD = 2,

    /// <summary>
    /// Евро.
    /// </summary>
    EUR = 3
}
