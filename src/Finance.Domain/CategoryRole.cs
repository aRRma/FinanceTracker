namespace Finance.Domain;

/// <summary>
/// Роль категории. Единственный признак, по которому «Прочее» и служебные категории
/// отличаются от обычных: строкового ключа стартового набора в базе нет, а название
/// пользователь вправе изменить.
/// </summary>
public enum CategoryRole
{
    /// <summary>Обычная категория: переименовывается, переносится, удаляется.</summary>
    Normal,

    /// <summary>Приёмник группы «Прочее»: сюда переезжают операции удаляемых подкатегорий.</summary>
    Other,

    /// <summary>Служебная категория. Служебной группе приёмник не нужен.</summary>
    Service
}
