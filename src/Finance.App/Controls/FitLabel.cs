namespace Finance.App.Controls;

/// <summary>
/// Подпись в одну строку, которая уменьшает кегль, пока текст не поместится по ширине.
/// Нужна там, где ширина строки фиксирована, а текст длиннее её при крупном масштабе
/// экрана или крупном шрифте системы: главная цифра формы операции (сумма бывает
/// до «999 999 999 999,99», и обычная подпись переносила хвост на невидимую строку,
/// оставляя на виду «−12 345») и сегменты вида операции.
/// </summary>
/// <remarks>
/// Подбор кегля делает сама платформа — автоподбор размера текста Android; включает
/// его отображение в <see cref="MauiProgram"/>. Верхний предел — <see cref="Label.FontSize"/>,
/// нижний — <see cref="MinimumSize"/>. Порог по числу знаков здесь не годится: ширина
/// знака зависит от масштаба экрана и шрифта системы, а платформа мерит настоящую.
/// Предел читается один раз, при создании платформенной подписи.
/// </remarks>
public sealed class FitLabel : Label
{
    /// <summary>
    /// Создаёт подпись в одну строку: с разрешённым переносом платформа не ужимает
    /// кегль, а переносит текст — «Перевод» в сегменте уезжал на вторую строку.
    /// </summary>
    public FitLabel() => MaxLines = 1;

    /// <summary>
    /// Меньше этого кегля текст не ужимается. По умолчанию 16 — для главной цифры:
    /// мельче сумма перестаёт быть главной на экране.
    /// </summary>
    public int MinimumSize { get; set; } = 16;
}
