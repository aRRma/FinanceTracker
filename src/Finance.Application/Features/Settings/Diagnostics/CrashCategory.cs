namespace Finance.Application.Features.Settings.Diagnostics;

/// <summary>
/// Вид сбоя на экране отчётов: что случилось глазами пользователя, а не откуда пришёл отчёт.
/// </summary>
/// <remarks>
/// Выводится из того, кто записал отчёт, и из причины завершения, которую назвала система. Одно
/// «приложение закрылось» приходит и от перехвата в приложении, и от системы, если перехват не успел.
/// </remarks>
public enum CrashCategory
{
    /// <summary>
    /// Вид не задан. Настоящим значением не бывает.
    /// </summary>
    Unknown = 0,

    /// <summary>
    /// Приложение закрылось на необработанном исключении .NET или Java.
    /// </summary>
    AppClosed = 1,

    /// <summary>
    /// Нативное падение в библиотеке Android.
    /// </summary>
    SystemFault = 2,

    /// <summary>
    /// Приложение зависло, и его закрыли в окне «не отвечает».
    /// </summary>
    Froze = 3,

    /// <summary>
    /// Система закрыла приложение сама, чаще всего в фоне: нехватка памяти, заморозка, сигнал.
    /// </summary>
    Killed = 4,

    /// <summary>
    /// Сбой действия или перечитывания экрана; приложение работает дальше.
    /// </summary>
    ActionFailed = 5,

    /// <summary>
    /// Сбой, которого никто не видел: забытая задача, фоновая работа.
    /// </summary>
    Warning = 6,
}
