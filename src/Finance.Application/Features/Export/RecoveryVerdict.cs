namespace Finance.Application.Features.Export;

/// <summary>
/// Подходит ли присланный файл для восстановления. Отказ — ожидаемый исход,
/// а не сбой: пользователь просто выбрал не тот файл.
/// </summary>
public enum RecoveryVerdict
{
    /// <summary>
    /// Не задано.
    /// </summary>
    Unknown = 0,

    /// <summary>
    /// Файл проверен и доведён до текущей схемы: можно восстанавливать.
    /// </summary>
    Ready = 1,

    /// <summary>
    /// Это не выгрузка трекера: не база SQLite или база без нашей истории миграций.
    /// </summary>
    NotExport = 2,

    /// <summary>
    /// База трекера, но испорченная: проверка целостности не прошла.
    /// </summary>
    Damaged = 3,

    /// <summary>
    /// Выгрузка из более новой версии приложения: в ней миграции, которых это приложение не знает.
    /// </summary>
    Newer = 4
}
