namespace Finance.Application.Infrastructure;

/// <summary>
/// Модель представления формы: у неё есть набранное, которое можно потерять.
/// </summary>
/// <remarks>
/// Отменить сохранение нечем, корзины нет, а «назад» на Android нажимают жестом
/// и промахом. Экран спрашивает подтверждение только когда терять есть что —
/// иначе вопрос появлялся бы при каждом выходе и его перестали бы читать.
/// </remarks>
public interface IFormModel
{
    /// <summary>
    /// Форму правили после загрузки, и уход с экрана потеряет правку.
    /// Считается сравнением с состоянием на момент загрузки: перечислять
    /// «какие свойства считаются правкой» значило бы забыть одно при первом
    /// же новом поле.
    /// </summary>
    bool IsDirty { get; }
}
