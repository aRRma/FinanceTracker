namespace Finance.Application.Infrastructure.Settings;

/// <summary>
/// Оформление приложения. Три состояния, а не переключатель «тёмная да/нет»:
/// вернуться к системной теме после ручного выбора иначе невозможно.
/// </summary>
public enum Theme
{
    /// <summary>
    /// Значение неинициализированной переменной. Выбором пользователя не бывает:
    /// незаданную и незнакомую настройку разбор сводит к <see cref="System"/>.
    /// </summary>
    Unknown = 0,

    /// <summary>
    /// Как в системе. Ею же оборачивается незаданная и незнакомая настройка.
    /// </summary>
    System = 1,

    /// <summary>
    /// Светлая независимо от системной.
    /// </summary>
    Light = 2,

    /// <summary>
    /// Тёмная независимо от системной.
    /// </summary>
    Dark = 3
}
