namespace Finance.Application.Infrastructure;

/// <summary>
/// Оповещение экранов об изменении данных. Событие приходит после фиксации
/// транзакции, а не до: экран, перечитавший себя внутри неоткатанной транзакции,
/// показал бы то, чего в базе может и не остаться.
/// </summary>
public interface IChangeNotifier
{
    /// <summary>
    /// Данные изменились. Доставка в поток интерфейса — забота подписчика.
    /// </summary>
    event Action<DataChange>? Changed;

    /// <summary>
    /// Номер последнего изменения среди видов <paramref name="kinds"/>; ноль — таких
    /// ещё не было. По нему экран, ушедший со своей подпиской, узнаёт на возврате,
    /// пропустил ли он что-нибудь.
    /// </summary>
    /// <param name="kinds">Виды изменений, которые интересуют экран.</param>
    long VersionOf(DataChange kinds);

    /// <summary>
    /// Сообщает об изменении. Зовёт <c>UnitOfWork</c> после фиксации команды; мимо него
    /// зовут только смена темы, смена пояса и возврат из фона, где транзакции нет.
    /// </summary>
    /// <param name="change">Что именно изменилось.</param>
    void Publish(DataChange change);
}
