namespace Finance.Application.Infrastructure;

/// <summary>
/// Модель экрана, где строки выделяют для действия над несколькими сразу.
/// </summary>
/// <remarks>
/// Выделение живёт, только пока пользователь на экране: «назад» снимает его,
/// а не уводит с экрана, и уход со страницы тоже. Иначе вернувшийся застал бы
/// отметки, о которых забыл, и удалил бы лишнее одним нажатием.
/// </remarks>
public interface ISelectionModel
{
    /// <summary>
    /// Включено выделение: касание строки отмечает её, а не открывает.
    /// </summary>
    bool IsSelecting { get; }

    /// <summary>
    /// Снимает выделение со всех строк и выключает его.
    /// </summary>
    void EndSelection();
}
