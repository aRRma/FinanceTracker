namespace Finance.Application.Infrastructure.Diagnostics;

/// <summary>
/// Откуда пришёл отчёт о сбое. В файле хранится именем, а не номером.
/// </summary>
public enum CrashKind
{
    /// <summary>
    /// Вид не задан. Настоящим значением не бывает.
    /// </summary>
    Unknown = 0,

    /// <summary>
    /// Пойманный: сбой действия или перечитывания экрана, пользователю показано общее сообщение.
    /// </summary>
    Caught = 1,

    /// <summary>
    /// Необработанное исключение .NET: после него процесс закрывается.
    /// </summary>
    Unhandled = 2,

    /// <summary>
    /// Исключение внутри Java: после него процесс закрывается.
    /// </summary>
    Java = 3,

    /// <summary>
    /// Предупреждение: процесс жив, но что-то пошло не так — например, забытая задача.
    /// </summary>
    Warning = 4,

    /// <summary>
    /// Причина прошлого завершения, которую система сообщила при следующем запуске.
    /// </summary>
    ExitReason = 5,
}
