namespace Finance.Application.Infrastructure;

/// <summary>
/// Модель представления, которая слушает изменения данных, пока её экран на виду.
/// </summary>
/// <remarks>
/// Подписка живёт не от создания до сборки мусора, а ровно от появления экрана
/// до его ухода: оповещение — одно на приложение, и модель, подписавшаяся
/// в конструкторе, остаётся в его списке навсегда. Каждый заход на экран добавлял
/// бы ещё одного слушателя, и одно изменение перечитывало бы данные десяток раз.
/// </remarks>
public interface IScreenModel
{
    /// <summary>
    /// Перечитать экран не удалось. Модель об этом сказать некому: перечитывание
    /// начинается не с действия пользователя, а с чужого изменения данных,
    /// и без этого события экран молча остался бы устаревшим.
    /// </summary>
    event Action<Exception>? ReloadFailed;

    /// <summary>Экран появился: подписаться на изменения.</summary>
    void Activate();

    /// <summary>Экран ушёл: отписаться.</summary>
    void Deactivate();
}
